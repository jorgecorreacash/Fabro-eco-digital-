export function normalizeThemeId(raw: string | null | undefined): ThemeMeta['id'] {
  if (!raw) return 'midnight-purple';
  const match = FABRO_THEMES.find((t) => t.id === raw);
  if (match) return match.id;
  return LEGACY_THEME_MAP[raw] || 'midnight-purple';
}

